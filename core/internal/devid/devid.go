var (
	// Corporate suffixes stripped (repeatedly) from the end of a name.
	reSuffix = regexp.MustCompile(`(?i)[\s,.]+(co|corp|corporation|corporate|inc|incorporated|ltd|limited|llc|l\.l\.c|gmbh|ag|s\.?a|b\.?v|pte|plc|oy|ab|kg|technologies|technology|tech|company)\.?$`)
	// Leading place names common in Chinese registrations.
	rePlace   = regexp.MustCompile(`(?i)^(shenzhen|hangzhou|guangzhou|guangdong|beijing|shanghai|zhuhai|dongguan|xiamen|fujian|chongqing|qingdao|suzhou|ningbo|nanjing|wuhan|chengdu|tianjin|jiangsu|zhejiang)\s+`)
	reTrailOf = regexp.MustCompile(`(?i),?\s+of\s+\S+$`) // "..., INC. OF ZHUHAI"
	reParen   = regexp.MustCompile(`\s*\([^)]*\)\s*`)
	reSpaces  = regexp.MustCompile(`\s+`)
)

// classify returns a short vendor name and a device-type guess.
func classify(full string) (short, hint string) {
	low := strings.ToLower(full)
	for _, b := range brands {
		if strings.Contains(low, b.match) {
			return b.short, b.hint
		}
	}
	return shorten(full), ""
}

// shorten trims a registry name to something readable in a table cell.
func shorten(full string) string {
	s := reParen.ReplaceAllString(full, " ")
	s = reTrailOf.ReplaceAllString(s, "")
	s = strings.TrimSpace(reSpaces.ReplaceAllString(s, " "))
	for {
		t := strings.TrimRight(reSuffix.ReplaceAllString(s, ""), " ,.")
		if t == s || t == "" {
			break
		}
		s = t
	}
	if t := rePlace.ReplaceAllString(s, ""); t != "" {
		s = t
	}
	if s == "" {
		return full
	}
	return s
}
